#!/usr/bin/env node
import { readFile, writeFile, readdir } from "node:fs/promises";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..");
const CONTENT_DIR = resolve(repo, "src/content");
const OUT = resolve(repo, "src/lib/tv-manifest.ts");

const EXCLUDED_BASENAMES = new Set([
  "tim-kelliher",
  "naveen-reddy",
  "noor-sachdev",
  "danvers-clinic",
  "bay-area-clinic",
]);

const IMAGE_RE = /\/assets\/[a-zA-Z0-9_\-./]+\.(?:webp|png|jpg|jpeg|avif)/g;

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(p);
    else if (entry.isFile() && entry.name.endsWith(".ts")) yield p;
  }
}

const found = new Set();
for await (const file of walk(CONTENT_DIR)) {
  const text = await readFile(file, "utf8");
  const matches = text.match(IMAGE_RE);
  if (!matches) continue;
  for (const m of matches) {
    const base = m.split("/").pop().replace(/\.(webp|png|jpg|jpeg|avif)$/i, "");
    if (EXCLUDED_BASENAMES.has(base)) continue;
    found.add(m);
  }
}

const sorted = Array.from(found).sort();

if (sorted.length < 5) {
  console.error(
    `[build-tv-manifest] Only ${sorted.length} eligible image(s) found; minimum is 5. Aborting.`,
  );
  process.exit(1);
}

const body =
  `// AUTO-GENERATED by scripts/build-tv-manifest.mjs — do not edit by hand.\n` +
  `// Eligible images for the /tv signage route. Excludes provider profile and\n` +
  `// location images. Re-run via "npm run build" or "npm run dev" (prebuild/predev).\n\n` +
  `export const tvImages = [\n` +
  sorted.map((p) => `  ${JSON.stringify(p)},`).join("\n") +
  `\n] as const;\n\n` +
  `export type TvImage = (typeof tvImages)[number];\n`;

await writeFile(OUT, body, "utf8");
console.log(`[build-tv-manifest] Wrote ${sorted.length} images → ${OUT}`);
